public enum TrackColumnGroup { Essentials, Listening, Credits, Details, Sorting, File }

// A column is offered only as a complete definition: defaults, cell content,
// sorting, and selector placement. Complex sorts keep their explicit handlers.
public sealed record TrackColumnDescriptor(
    string Id, string Header, double Width, double MinWidth, bool Visible, int Order,
    TrackColumnGroup Group, int SelectorOrder, Func<TrackRowViewModel, string?> CellText,
    Func<IEnumerable<ListedTrack>, bool, bool, IEnumerable<ListedTrack>> Sort)
{
    public MusicColumnDefinition CreateColumn() => new(Id, Header, Width, MinWidth, Visible, Order);
}

